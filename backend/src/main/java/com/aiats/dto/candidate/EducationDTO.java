package com.aiats.dto.candidate;
public class EducationDTO {
    private String id; private String degree; private String institution; private String fieldOfStudy; private String startYear; private String endYear; private String grade;
    public String getId() { return id; } public void setId(String id) { this.id = id; }
    public String getDegree() { return degree; } public void setDegree(String degree) { this.degree = degree; }
    public String getInstitution() { return institution; } public void setInstitution(String institution) { this.institution = institution; }
    public String getFieldOfStudy() { return fieldOfStudy; } public void setFieldOfStudy(String fieldOfStudy) { this.fieldOfStudy = fieldOfStudy; }
    public String getStartYear() { return startYear; } public void setStartYear(String startYear) { this.startYear = startYear; }
    public String getEndYear() { return endYear; } public void setEndYear(String endYear) { this.endYear = endYear; }
    public String getGrade() { return grade; } public void setGrade(String grade) { this.grade = grade; }
}
