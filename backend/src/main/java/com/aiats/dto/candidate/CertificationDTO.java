package com.aiats.dto.candidate;
public class CertificationDTO {
    private String id; private String title; private String issuer; private String issueDate; private String credentialUrl; private String credentialId;
    public String getId() { return id; } public void setId(String id) { this.id = id; }
    public String getTitle() { return title; } public void setTitle(String title) { this.title = title; }
    public String getIssuer() { return issuer; } public void setIssuer(String issuer) { this.issuer = issuer; }
    public String getIssueDate() { return issueDate; } public void setIssueDate(String issueDate) { this.issueDate = issueDate; }
    public String getCredentialUrl() { return credentialUrl; } public void setCredentialUrl(String credentialUrl) { this.credentialUrl = credentialUrl; }
    public String getCredentialId() { return credentialId; } public void setCredentialId(String credentialId) { this.credentialId = credentialId; }
}
